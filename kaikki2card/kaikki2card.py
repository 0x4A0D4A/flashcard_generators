#!/usr/bin/env python3
"""
kaikki2card - Build flashcards from a locally stored copy of Wiktionary data

Instead of scraping Wiktionary live (see ../wikt2card), download kaikki.org's
pre-extracted English-Wiktionary dump once, filter it by language into a
local SQLite database, and look words up offline.

Usage:
    kaikki2card fetch
    kaikki2card build --lang ga
    kaikki2card lookup --lang ga bean
    kaikki2card resolve --lang ga text.txt
    kaikki2card cards --lang ga text.txt [--anki --deck DECK]

Data lives in $XDG_DATA_HOME/kaikki (default ~/.local/share/kaikki).
"""

import argparse
import gzip
import json
import logging
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Dict, Optional

log = logging.getLogger('kaikki2card')


# ============================================================================
# Paths and constants
# ============================================================================

RAW_URL = "https://kaikki.org/dictionary/raw-wiktextract-data.jsonl.gz"
USER_AGENT = "kaikki2card/0.1 (https://github.com/0x4A0D4A/flashcard_generators)"

# Size measured by a HEAD request on 2026-11-05. The file is regenerated by
# kaikki.org, so a different size is only a warning, never an error.
EXPECTED_RAW_SIZE = 3_082_476_978


def data_dir() -> Path:
    """Directory for the (large) downloaded data and derived database"""
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "kaikki"


def raw_path() -> Path:
    return data_dir() / "raw" / "raw-wiktextract-data.jsonl.gz"


def meta_path() -> Path:
    return data_dir() / "raw" / "raw-wiktextract-data.meta.json"


# ============================================================================
# fetch
# ============================================================================

def head_info(url: str) -> Dict[str, Optional[str]]:
    """HEAD the URL and return Content-Length / Last-Modified (best effort)"""
    out = subprocess.run(
        ["curl", "-sIL", "-A", USER_AGENT, "--max-time", "60", url],
        capture_output=True, text=True,
    ).stdout
    info: Dict[str, Optional[str]] = {"content-length": None, "last-modified": None}
    for line in out.splitlines():
        key, _, value = line.partition(":")
        key = key.strip().lower()
        if key in info:
            info[key] = value.strip()  # keep the last response's value
    return info


def cmd_fetch(args) -> int:
    """Download the raw kaikki.org dump (resumable, sequential)"""
    dest = raw_path()
    dest.parent.mkdir(parents=True, exist_ok=True)

    info = head_info(RAW_URL)
    remote_size = int(info["content-length"]) if info["content-length"] else None
    print(f"Remote: {remote_size} bytes, last-modified {info['last-modified']}")
    if remote_size and remote_size != EXPECTED_RAW_SIZE:
        print(f"Note: size differs from the {EXPECTED_RAW_SIZE} bytes seen on 2026-11-05 "
              f"(kaikki.org regenerates this file).")

    # -C - resumes a partial download; -f fails on HTTP errors
    cmd = ["curl", "-fL", "-C", "-", "--retry", "3", "-A", USER_AGENT,
           "-o", str(dest), RAW_URL]
    print(f"Downloading to {dest}")
    if subprocess.run(cmd).returncode != 0:
        print("Error: download failed (re-run to resume)")
        return 1

    size = dest.stat().st_size
    if remote_size and size != remote_size:
        print(f"Error: downloaded {size} bytes, expected {remote_size}")
        return 1

    meta_path().write_text(json.dumps({
        "url": RAW_URL,
        "size": size,
        "last_modified": info["last-modified"],
        "fetched_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
    }, indent=2))
    print(f"OK: {size} bytes")
    return 0


# ============================================================================
# extract: one streaming pass over the raw dump, keeping a single language
# ============================================================================

try:
    import orjson as _json_fast
    _loads = _json_fast.loads
except ImportError:  # stdlib fallback; slower but fine for the first pass
    _loads = json.loads


def subset_path(lang: str) -> Path:
    return data_dir() / f"{lang}.jsonl.gz"


def extract_language(lang: str, src: Path, dest: Path) -> Dict[str, float]:
    """Copy the entries of one language from the raw dump into a small file.

    Entries *about* other languages (e.g. English words that merely list an
    Irish translation) contain the same ``"lang_code": "ga"`` text, so a cheap
    substring test selects candidates and the parsed top-level ``lang_code``
    decides. The raw file is streamed and never written out uncompressed.
    """
    needle = f'"lang_code": "{lang}"'.encode()
    started = time.time()
    scanned = candidates = kept = 0
    tmp = dest.with_suffix(dest.suffix + ".part")
    dest.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(src, "rb") as fin, gzip.open(tmp, "wb") as fout:
        for line in fin:
            scanned += 1
            if needle not in line:
                continue
            candidates += 1
            if _loads(line).get("lang_code") == lang:
                fout.write(line)
                kept += 1
            if scanned % 1_000_000 == 0:
                log.debug(f"scanned {scanned:,} lines, kept {kept:,}")
    tmp.replace(dest)  # only a complete file ever has the final name
    return {"scanned": scanned, "candidates": candidates, "kept": kept,
            "seconds": time.time() - started}


def cmd_extract(args) -> int:
    """Write <lang>.jsonl.gz containing only that language's entries"""
    src = raw_path()
    if not src.exists():
        print(f"Error: {src} not found; run `kaikki2card fetch` first")
        return 1
    dest = subset_path(args.lang)
    stats = extract_language(args.lang, src, dest)
    print(f"Scanned {stats['scanned']:,} lines in {stats['seconds']:.0f}s; "
          f"kept {stats['kept']:,} '{args.lang}' entries "
          f"({stats['candidates']:,} substring candidates) -> {dest} "
          f"({dest.stat().st_size / 1e6:.1f} MB)")
    return 0


# ============================================================================
# build: load a language into SQLite
# ============================================================================

import sqlite3

# Form markers that are template noise, not real inflected forms
JUNK_FORM_TAGS = {"table-tags", "inflection-template", "error-unrecognized-form"}

SCHEMA = """
CREATE TABLE IF NOT EXISTS entries (
    id    INTEGER PRIMARY KEY,
    lang  TEXT NOT NULL,
    word  TEXT NOT NULL,
    pos   TEXT,
    data  TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS forms (
    form     TEXT NOT NULL,
    lang     TEXT NOT NULL,
    entry_id INTEGER NOT NULL,
    tags     TEXT
);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT);
"""


def db_path() -> Path:
    return data_dir() / "kaikki.sqlite"


def _word_list(items) -> list:
    """['word', ...] from kaikki's [{'word': ..., ...}, ...] lists"""
    out = []
    for item in items or []:
        word = item.get("word") if isinstance(item, dict) else item
        if word and word not in out:
            out.append(word)
    return out


def compact_entry(entry: dict) -> dict:
    """Reduce a raw entry to the fields cards need (drops templates etc.)"""
    senses = []
    synonyms = _word_list(entry.get("synonyms"))
    antonyms = _word_list(entry.get("antonyms"))
    for sense in entry.get("senses", []):
        glosses = sense.get("glosses") or []
        if not glosses:
            continue
        examples = []
        for ex in sense.get("examples", []):
            if ex.get("type") == "quotation" or not ex.get("text"):
                continue  # citations with references are not card material
            examples.append({
                "text": ex["text"],
                "translation": ex.get("english") or ex.get("translation") or "",
            })
        senses.append({
            "glosses": glosses,
            "tags": [t for t in sense.get("tags", []) if t not in ("form-of", "alt-of")],
            "examples": examples,
            "form_of": _word_list(sense.get("form_of")),
            "alt_of": _word_list(sense.get("alt_of")),
        })
        for word in _word_list(sense.get("synonyms")):
            if word not in synonyms:
                synonyms.append(word)
        for word in _word_list(sense.get("antonyms")):
            if word not in antonyms:
                antonyms.append(word)

    sounds = []
    for sound in entry.get("sounds", []):
        keep = {k: sound[k] for k in ("ipa", "tags", "audio", "ogg_url", "mp3_url") if sound.get(k)}
        if "ipa" in keep or "audio" in keep:
            sounds.append(keep)

    return {
        "senses": senses,
        "sounds": sounds,
        "etymology": (entry.get("etymology_text") or "").strip(),
        "synonyms": synonyms,
        "antonyms": antonyms,
        "derived": _word_list(entry.get("derived")),
        "related": _word_list(entry.get("related")),
    }


def usable_forms(entry: dict) -> list:
    """(form, tags) pairs worth indexing: single words, no template junk"""
    out = []
    seen = set()
    for f in entry.get("forms", []):
        form = (f.get("form") or "").strip()
        tags = f.get("tags") or []
        if not form or " " in form or form == entry["word"]:
            continue
        if JUNK_FORM_TAGS & set(tags):
            continue
        key = (form, " ".join(tags))
        if key not in seen:
            seen.add(key)
            out.append((form, " ".join(tags)))
    return out


def load_language(conn: sqlite3.Connection, lang: str, lines) -> Dict[str, int]:
    """Replace everything stored for `lang` with the entries in `lines`"""
    conn.executescript(SCHEMA)
    conn.execute("DELETE FROM forms WHERE lang = ?", (lang,))
    conn.execute("DELETE FROM entries WHERE lang = ?", (lang,))
    entries = forms = 0
    for line in lines:
        raw = _loads(line)
        if raw.get("lang_code") != lang:
            continue
        cur = conn.execute(
            "INSERT INTO entries (lang, word, pos, data) VALUES (?, ?, ?, ?)",
            (lang, raw["word"], raw.get("pos"),
             json.dumps(compact_entry(raw), ensure_ascii=False, separators=(",", ":"))),
        )
        entries += 1
        rows = [(form, lang, cur.lastrowid, tags) for form, tags in usable_forms(raw)]
        conn.executemany("INSERT INTO forms VALUES (?, ?, ?, ?)", rows)
        forms += len(rows)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_entries_word ON entries (lang, word)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_forms_form ON forms (lang, form)")
    return {"entries": entries, "forms": forms}


def cmd_build(args) -> int:
    """Build/refresh the database for one language"""
    started = time.time()
    sub = subset_path(args.lang)
    if args.refresh or not sub.exists():
        rc = cmd_extract(args)
        if rc:
            return rc
    conn = sqlite3.connect(db_path())
    try:
        with gzip.open(sub, "rb") as fin:
            counts = load_language(conn, args.lang, fin)
        meta = {}
        if meta_path().exists():
            meta = json.loads(meta_path().read_text())
        for key, value in (
            (f"{args.lang}:built_at", time.strftime("%Y-%m-%dT%H:%M:%S%z")),
            (f"{args.lang}:source_last_modified", str(meta.get("last_modified"))),
            (f"{args.lang}:source_size", str(meta.get("size"))),
            (f"{args.lang}:entries", str(counts["entries"])),
        ):
            conn.execute("INSERT OR REPLACE INTO meta VALUES (?, ?)", (key, value))
        conn.commit()
        conn.execute("VACUUM")
    finally:
        conn.close()
    print(f"Built '{args.lang}': {counts['entries']:,} entries, {counts['forms']:,} forms "
          f"in {time.time() - started:.1f}s -> {db_path()} "
          f"({db_path().stat().st_size / 1e6:.1f} MB)")
    return 0


# ============================================================================
# CLI
# ============================================================================

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build flashcards from a local copy of Wiktionary data (kaikki.org)")
    parser.add_argument('-v', '--verbose', action='store_true', help='Debug output')
    sub = parser.add_subparsers(dest='command', required=True)

    sub.add_parser('fetch', help='Download the raw kaikki.org dump').set_defaults(func=cmd_fetch)

    p = sub.add_parser('extract', help='Copy one language out of the raw dump')
    p.add_argument('--lang', required=True, help='Wiktionary language code (e.g. ga, fr, ja)')
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser('build', help='Load one language into the SQLite database')
    p.add_argument('--lang', required=True, help='Wiktionary language code (e.g. ga, fr, ja)')
    p.add_argument('--refresh', action='store_true',
                   help='Re-extract the language from the raw dump first')
    p.set_defaults(func=cmd_build)
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.WARNING,
                        format='%(message)s')
    try:
        return args.func(args)
    except KeyboardInterrupt:
        print("\nAborted.")
        return 130


if __name__ == '__main__':
    sys.exit(main())
